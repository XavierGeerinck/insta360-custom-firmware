#!/usr/bin/env python3
"""Map Tabler icon names to code points.

    icons.py range <tabler-icons.css> <tabler-icons-filled.css> outline|filled
                                         -> lv_font_conv range list for that face
    icons.py rust  <tabler-icons.css> <tabler-icons-filled.css>
                                         -> src/kit/icons.rs

A name ending in "-filled" comes from Tabler's filled face (a separate font
with its own code points); every other name from the outline face.
"""
import re
import sys

ICONS = [  # (Rust constant, Tabler name)
    ("MIC", "microphone"), ("MIC_OFF", "microphone-off"), ("MARK", "bookmark"),
    ("VOLUME_LOW", "volume-2"), ("VOLUME_HIGH", "volume"), ("VOLUME_OFF", "volume-off"),
    ("LOCK", "lock"), ("WIFI", "wifi"), ("WIFI_OFF", "wifi-off"),
    ("BLUETOOTH", "bluetooth"), ("USB", "usb"),
    ("BATTERY_0", "battery"), ("BATTERY_1", "battery-1"), ("BATTERY_2", "battery-2"),
    ("BATTERY_3", "battery-3"), ("BATTERY_4", "battery-4"), ("BATTERY_CHARGING", "battery-charging"),
    ("PLAY", "player-play-filled"), ("PAUSE", "player-pause-filled"), ("STOP", "player-stop-filled"),
    ("RECORD", "player-record-filled"),
    ("LEFT", "chevron-left"), ("RIGHT", "chevron-right"), ("DOWN", "chevron-down"),
    ("CHECK_CIRCLE", "circle-check"), ("CHECK", "check"), ("CLOCK", "clock"),
    ("ALERT", "alert-triangle"), ("INFO", "info-circle"),
    ("DEVICE", "database"), ("SEND", "upload"), ("TRASH", "trash"), ("POWER", "power"),
    ("PHONE", "phone"), ("PHONE_OFF", "phone-off"), ("FOLDER", "folder"), ("REFRESH", "refresh"),
    ("LAPTOP", "device-laptop"), ("MOBILE", "device-mobile"), ("SUN", "sun"),
    ("BACKSPACE", "backspace"), ("MINUS", "minus"), ("PLUS", "plus"),
    ("NOISE", "wave-sine"), ("PATTERN", "ear"), ("SETTINGS", "settings"),
    ("HEIGHT", "arrows-vertical"), ("DOT", "circle-dot"),
]


FILLED = "-filled"


def table(css):
    return dict(re.findall(r'\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";', css))


def codepoints(css, filled_css):
    """(Rust constant, Tabler name, code point, face) for every icon."""
    faces = {"outline": table(css), "filled": table(filled_css)}
    found = []
    for const, name in ICONS:
        face, base = ("filled", name[: -len(FILLED)]) if name.endswith(FILLED) else ("outline", name)
        if base not in faces[face]:
            sys.exit(f"tabler {face} icon not found: {base}")
        found.append((const, name, int(faces[face][base], 16), face))
    return found


def read(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def main():
    mode, css_path, filled_path = sys.argv[1], sys.argv[2], sys.argv[3]
    icons = codepoints(read(css_path), read(filled_path))
    if mode == "range":
        face = sys.argv[4]
        print(",".join(f"0x{cp:X}" for _, _, cp, f in icons if f == face))
    elif mode == "rust":
        print("//! Tabler icon code points. Generated by fonts/icons.py; do not edit.")
        print("//! Render them with one of the `Font::Icon*` fonts.")
        print()
        for const, name, cp, _ in icons:
            print(f"/// Tabler `{name}`")
            print(f'pub const {const}: &str = "\\u{{{cp:x}}}";')
        print()
        print("/// Every icon, for glyph-coverage tests.")
        # One name per line, as rustfmt lays out a list this long.
        print("pub const ALL: &[&str] = &[")
        for const, _, _, _ in icons:
            print(f"    {const},")
        print("];")
    else:
        sys.exit("usage: icons.py range|rust <tabler-icons.css> <tabler-icons-filled.css> [outline|filled]")


if __name__ == "__main__":
    main()
