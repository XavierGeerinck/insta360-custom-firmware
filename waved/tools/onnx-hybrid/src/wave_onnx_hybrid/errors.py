"""Stable error taxonomy for the host-only ONNX hybrid PoC."""

from __future__ import annotations

from enum import StrEnum
from typing import Any


class ErrorCode(StrEnum):
    EVIDENCE_INVALID = "EVIDENCE_INVALID"
    POLICY_INVALID = "POLICY_INVALID"
    ONNX_MODEL_LIMIT = "ONNX_MODEL_LIMIT"
    ONNX_PARSE_FAILURE = "ONNX_PARSE_FAILURE"
    ONNX_CHECK_FAILURE = "ONNX_CHECK_FAILURE"
    ONNX_GRAPH_INVALID = "ONNX_GRAPH_INVALID"
    ONNX_EXTERNAL_DATA = "ONNX_EXTERNAL_DATA"
    ONNX_SHAPE_UNSUPPORTED = "ONNX_SHAPE_UNSUPPORTED"
    ONNX_TYPE_UNSUPPORTED = "ONNX_TYPE_UNSUPPORTED"
    ONNX_OPERATOR_UNSUPPORTED = "ONNX_OPERATOR_UNSUPPORTED"
    ONNX_QUANTIZATION_UNSUPPORTED = "ONNX_QUANTIZATION_UNSUPPORTED"
    ONNX_INPUT_INVALID = "ONNX_INPUT_INVALID"
    ONNX_OUTPUT_INVALID = "ONNX_OUTPUT_INVALID"
    PARTITION_NOT_PREFLIGHTED = "PARTITION_NOT_PREFLIGHTED"
    PARTITION_COMPILE_FAILURE = "PARTITION_COMPILE_FAILURE"
    PARTITION_NOT_NPU_RESIDENT = "PARTITION_NOT_NPU_RESIDENT"
    CPU_FALLBACK_FAILURE = "CPU_FALLBACK_FAILURE"
    OUTPUT_EXISTS = "OUTPUT_EXISTS"
    MODEL_PACKAGE_INVALID = "MODEL_PACKAGE_INVALID"
    MODEL_WEIGHT_HASH_MISMATCH = "MODEL_WEIGHT_HASH_MISMATCH"
    MODEL_STATE_VERSION_MISMATCH = "MODEL_STATE_VERSION_MISMATCH"
    NBG_SIGNATURE_NOT_APPROVED = "NBG_SIGNATURE_NOT_APPROVED"
    NBG_TENSOR_CONTRACT_MISMATCH = "NBG_TENSOR_CONTRACT_MISMATCH"
    NPU_INPUT_QUANTIZATION_MISMATCH = "NPU_INPUT_QUANTIZATION_MISMATCH"
    NPU_OUTPUT_QUANTIZATION_MISMATCH = "NPU_OUTPUT_QUANTIZATION_MISMATCH"
    NPU_OUTPUT_NONMONOTONIC = "NPU_OUTPUT_NONMONOTONIC"
    NPU_OUTPUT_NUMERICAL_MISMATCH = "NPU_OUTPUT_NUMERICAL_MISMATCH"
    AUDIO_RECONSTRUCTION_MISMATCH = "AUDIO_RECONSTRUCTION_MISMATCH"
    AUDIO_QUALITY_GATE_FAILURE = "AUDIO_QUALITY_GATE_FAILURE"
    AUDIO_REALTIME_GATE_FAILURE = "AUDIO_REALTIME_GATE_FAILURE"


class HybridError(RuntimeError):
    """A failure with a stable machine category and bounded details."""

    def __init__(
        self,
        code: ErrorCode,
        message: str,
        *,
        details: dict[str, Any] | None = None,
    ) -> None:
        self.code = code
        self.details = details or {}
        super().__init__(f"{code.value}: {message}")

    def to_document(self) -> dict[str, Any]:
        return {
            "code": self.code.value,
            "message": str(self).split(": ", 1)[1],
            "details": self.details,
        }
